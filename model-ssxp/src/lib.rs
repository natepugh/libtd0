#[cfg(test)]
mod tests {
    use super::common::SSXPTD0File;
    use libtd0_core::TD0File;

    #[test]
    fn test_ssxp_td0file_new() {
        let td0file = SSXPTD0File::new().expect("Test is broken.");
        #[rustfmt::skip]
        let expected: [u8; 128] = [
            // | 30u16|  T      D     0     a   0 (x 10)
            0x1e, 0x00, 0x54, 0x44, 0x30, 0x61, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            // H   D    R     a      S     S     X     P  | 32-bit chunk pos (32) || 32-bit chunk size (80) |
            0x48, 0x44, 0x52, 0x61, 0x53, 0x53, 0x58, 0x50, 0x20, 0x00, 0x00, 0x00, 0x50, 0x00, 0x00, 0x00,
            // 1u32 (item)         |  64u32 (item size)     | 16u32 first item offset | (unknown data)
            0x01, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00,   0x10, 0x00, 0x00, 0x00,   0x00, 0x00, 0x00, 0x00,
            // S   S     X     P     R     O     K     T  (16-char backup type, \0 padded.)
            0x53, 0x53, 0x58, 0x50, 0x52, 0x4f, 0x4b, 0x54, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            // U   S     E     R           K     I     T   (16-char backup name, '.' (0x2e) padded.)
            0x55, 0x53, 0x45, 0x52, 0x20, 0x4b, 0x49, 0x54, 0x2e, 0x2e, 0x2e, 0x2e, 0x2e, 0x2e, 0x2e, 0x2e,
            // | Firmware revision |     Build number     |  Device Serial Number '.' padded |
            // 1   .     1     0     0     0     8     3     X     X     X     X     X     X     X
            0x31, 0x2e, 0x31, 0x30, 0x30, 0x30, 0x38, 0x33, 0x58, 0x58, 0x58, 0x58, 0x58, 0x58, 0x58, 0x2e,
            // End of HDRa chunk marker (16x 0xff).
            0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
            // MD5 hash.
            0xB1, 0x96, 0xA5, 0x76, 0xBA, 0x7E, 0x55, 0xE3, 0x6D, 0x4E, 0x56, 0x36, 0x03, 0x43, 0x30, 0x7C,
        ];
        assert_eq!(td0file.try_into_bytes().unwrap(), expected);
    }

    #[test]
    fn test_ssxp_td0file_new_is_valid() {
        let td0file = SSXPTD0File::new().expect("Test is broken.");
        assert_eq!(Ok(()), td0file.validate_load());
    }
}
